ANSWER_SCHEMA = json.loads(Path(DESTINATION_ANSWER_SCHEMA_PATH).read_text())
REQUEST_SCHEMA = json.loads(Path(DESTINATION_REQUEST_SCHEMA_PATH).read_text())
PRODUCER = Producer(name="architecture-intelligence-platform", version="0.7.1", build_revision="t")
SNAPSHOT = SnapshotRef(
    snapshot_id="aip:snapshot:v1:" + "1" * 64, model_revision="sha256:" + "1" * 64
)
OTHER_SNAPSHOT = "aip:snapshot:v1:" + "2" * 64
BROKER, ENV = "kafka:cluster-a", "prod"
TOPIC, OTHER_TOPIC = "topic:owned:" + "a" * 64, "topic:owned:" + "b" * 64
CAPTURE_PROD = "urn:aip:source:kafka-consumer-state:" + "c" * 64
CAPTURE_STAGING = "urn:aip:source:kafka-consumer-state:" + "d" * 64
EVIDENCE_PROD = "kafka-capture:owned:" + "c" * 64
EVIDENCE_STAGING = "kafka-capture:owned:" + "d" * 64
T_PROD, T_STAGING = "2026-10-18T09:00:00Z", "2026-10-18T08:00:00Z"
MAP_EVIDENCE = "kafka-service-mapping-evidence:owned:" + "e" * 64


def _consumer(n: int) -> str:
    return "consumer:" + f"{n:064x}"


def _attachment(n: int, topic: str = TOPIC) -> dict:
    return {
        "id": f"kafka-attachment:owned:{n:063x}{topic[-1]}",
        "consumer_id": _consumer(n),
        "topic_id": topic,
        "captured_at": T_STAGING if n >= 100 else T_PROD,
        "evidence_ids": [EVIDENCE_STAGING if n >= 100 else EVIDENCE_PROD],
        "source_instance_id": CAPTURE_STAGING if n >= 100 else CAPTURE_PROD,
    }


def _group(n: int, environment: str = ENV) -> dict:
    return {
        "id": _consumer(n),
        "group_id": f"group-{n}",
        "broker_id": BROKER,
        "environment": environment,
    }


def _capture(source: str, evidence: str, environment: str, t: str) -> dict:
    return {
        "id": evidence,
        "source_instance_id": source,
        "broker_id": BROKER,
        "environment": environment,
        "captured_at": t,
        "source_revision": f"kafka:not-established+capture:{t}",
        "scope_digest": "f" * 64,
    }


def _entry(n: int, letter: str = "1") -> str:
    return f"kafka-service-mapping:owned:{n:063x}{letter}"


def _state(*, attachments, groups, captures=None, block=None, protocol=None) -> dict:
    state = {
        "topics": [
            {"id": TOPIC, "name": "inventory", **({"protocol": protocol} if protocol else {})},
            {"id": OTHER_TOPIC, "name": "audit"},
        ],
        "queues": [{"id": "queue:owned:" + "9" * 64, "name": "jobs"}],
        "kafka_consumer_state_v1": {
            "groups": groups,
            "attachments": attachments,
            "evidence": captures
            if captures is not None
            else [_capture(CAPTURE_PROD, EVIDENCE_PROD, ENV, T_PROD)],
        },
    }
    if block is not None:
        state["kafka_consumer_attribution_v1"] = block
    return state


def _block(attributions: list[dict], *, mapping_environment: str = ENV) -> dict:
    """An I2 block as the I2 projection writes it (rows authored here, not computed)."""
    return {
        "rule": {"id": "kafka-consumer-attribution", "version": "1"},
        "mapping_sources": [
            {"id": MAP_EVIDENCE, "broker_id": BROKER, "environment": mapping_environment}
        ],
        "attributions": attributions,
    }


def _attribution(n: int, outcome: str, *, entries=(), service_id=None, reason=None, limitations=()):
    attachment = _attachment(n)
    row = {
        "id": attachment["id"],
        "consumer_id": attachment["consumer_id"],
        "topic_id": attachment["topic_id"],
        "captured_at": attachment["captured_at"],
        "outcome": outcome,
        "limitations": [{"entry_id": e, "reason": r} for e, r in limitations],
        "attachment_evidence_ids": attachment["evidence_ids"],
        "mapping_entries": [{"id": e, "evidence_ids": [MAP_EVIDENCE]} for e in entries],
    }
    if service_id:
        row["service_id"] = service_id
    if reason:
        row["reason"] = reason
    return row


def _request(**overrides) -> DestinationConsumersQueryRequest:
    payload = {"mode": "query", "destination_id": TOPIC, "broker_id": BROKER, "environment": ENV}
    payload.update(overrides)
    jsonschema.validate(payload, REQUEST_SCHEMA)
    return DestinationConsumersQueryRequest.model_validate(payload)


def _answer(state, request=None, *, brokers=(BROKER,)) -> dict:
    """`brokers`: the declared brokers of TOPIC in `kafka_topic_brokers_v1` (when Kafka state
    exists)."""
    if "kafka_consumer_state_v1" in state:
        state = {
            **state,
            "kafka_topic_brokers_v1": sorted(
                [{"topic_id": TOPIC, "broker_id": b} for b in brokers]
                + [{"topic_id": OTHER_TOPIC, "broker_id": BROKER}],
                key=lambda row: (row["topic_id"], row["broker_id"]),
            ),
        }
    answer = project_destination_consumers(
        request or _request(), state, snapshot=SNAPSHOT, producer=PRODUCER
    )
    wire = json.loads(answer.model_dump_json())
    jsonschema.validate(wire, ANSWER_SCHEMA)
    return wire


def _with_brokers(state: dict) -> dict:
    return {
        **state,
        "kafka_topic_brokers_v1": [
            {"topic_id": TOPIC, "broker_id": BROKER},
            {"topic_id": OTHER_TOPIC, "broker_id": BROKER},
        ],
    }


def _codes(answer: dict) -> list[str]:
    return [item["code"] for item in answer["limitations"]]


def _ref(kind: EvidenceKind, ids: list[str], context: RequestContext | None = None) -> str:
    context = context or _request().context()
    return evidence_ref(
        snapshot_id=SNAPSHOT.snapshot_id,
        query_digest=query_context_digest(context),
        kind=kind,
        internal_ids=ids,
    )


