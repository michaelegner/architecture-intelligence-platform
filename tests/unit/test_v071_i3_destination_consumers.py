def _three() -> dict:
    return _state(
        attachments=[_attachment(n) for n in (3, 1, 2)], groups=[_group(n) for n in (1, 2, 3)]
    )


def test_paging_is_ordered_and_bound_to_snapshot_and_context() -> None:
    first = _answer(_three(), _request(limit=2))
    assert [row["consumer_id"] for row in first["data"]["rows"]] == [_consumer(1), _consumer(2)]
    assert "MORE_ROWS_AVAILABLE" in _codes(first)
    cursor = first["data"]["page"]["next_cursor"]
    second = _answer(_three(), _request(limit=2, cursor=cursor, snapshot_id=SNAPSHOT.snapshot_id))
    assert [row["consumer_id"] for row in second["data"]["rows"]] == [_consumer(3)]
    assert "next_cursor" not in second["data"]["page"]
    assert "MORE_ROWS_AVAILABLE" not in _codes(second)
    # Another Topic in the same broker and environment: answerable, but not this cursor's query.
    other_context = _request(
        destination_id=OTHER_TOPIC, cursor=cursor, snapshot_id=SNAPSHOT.snapshot_id
    )
    assert _codes(_answer(_three(), other_context)) == ["CURSOR_QUERY_MISMATCH"]


def test_a_cursor_without_snapshot_id_is_an_invalid_request() -> None:
    cursor = _answer(_three(), _request(limit=1))["data"]["page"]["next_cursor"]
    with pytest.raises(ValidationError):
        DestinationConsumersQueryRequest.model_validate(
            {"mode": "query", "destination_id": TOPIC, "broker_id": BROKER, "environment": ENV, "cursor": cursor}
        )  # fmt: skip


def test_a_cursor_from_another_snapshot_is_stale() -> None:
    older = SnapshotRef(snapshot_id=OTHER_SNAPSHOT, model_revision="sha256:" + "2" * 64)
    stale = project_destination_consumers(
        _request(limit=1), _with_brokers(_three()), snapshot=older, producer=PRODUCER
    ).data
    assert stale is not None and stale.page.next_cursor is not None
    request = _request(limit=1, cursor=stale.page.next_cursor, snapshot_id=SNAPSHOT.snapshot_id)
    assert _codes(_answer(_three(), request)) == ["SNAPSHOT_NOT_AVAILABLE"]


def test_evidence_refs_are_bound_to_the_snapshot() -> None:
    """Within one snapshot an attachment is visible in exactly one query context, so I3.1 can only
    show snapshot binding; context binding is exercised by the I3.2 evidence mode."""
    block = _block([_attribution(1, "RESOLVED", entries=[_entry(1)], service_id="service:stock")])
    state = _state(attachments=[_attachment(1)], groups=[_group(1)], block=block)
    older = SnapshotRef(snapshot_id=OTHER_SNAPSHOT, model_revision="sha256:" + "2" * 64)
    current = _answer(state)["data"]["rows"][0]
    previous = project_destination_consumers(
        _request(), _with_brokers(state), snapshot=older, producer=PRODUCER
    ).data
    assert previous is not None
    [row] = previous.rows
    assert set(row.attachment_evidence_refs).isdisjoint(current["attachment_evidence_refs"])
    assert set(row.mapping_evidence_refs).isdisjoint(current["mapping_evidence_refs"])


