def _valid_wire() -> dict:
    block = _block([_attribution(1, "UNRESOLVED", reason="NO_MAPPING")])
    return _answer(_state(attachments=[_attachment(1)], groups=[_group(1)], block=block))


def _set_codes(wire: dict, codes: list[str]) -> None:
    wire["limitations"] = [{"code": code, "message": "m"} for code in sorted(codes)]


def _without_mapping_source(wire: dict) -> None:
    wire["data"]["mapping_source_present"] = False  # but NO_MAPPING_SOURCE is not listed


def _spurious_no_mapping_source(wire: dict) -> None:
    _set_codes(wire, ["CAPTURE_SCOPE_LIMITED", "NO_MAPPING_SOURCE"])


def _spurious_more_rows(wire: dict) -> None:
    _set_codes(wire, ["CAPTURE_SCOPE_LIMITED", "MORE_ROWS_AVAILABLE"])


def _evidence_code_in_query(wire: dict) -> None:
    _set_codes(wire, ["CAPTURE_SCOPE_LIMITED", "EVIDENCE_REF_NOT_RESOLVED"])


def _answered_outcome(wire: dict) -> None:
    wire["outcome"] = "ANSWERED"


def _missing_scope_limitation(wire: dict) -> None:
    _set_codes(wire, [])


def _refusal_with_data(wire: dict) -> None:
    _set_codes(wire, ["UNKNOWN_DESTINATION"])
    wire["outcome"] = "NOT_ANSWERED"


def _service_on_unresolved_row(wire: dict) -> None:
    wire["data"]["rows"][0]["service_id"] = "service:stock"


@pytest.mark.parametrize(
    "mutate",
    [
        _without_mapping_source,
        _spurious_no_mapping_source,
        _spurious_more_rows,
        _evidence_code_in_query,
        _answered_outcome,
        _missing_scope_limitation,
        _refusal_with_data,
        _service_on_unresolved_row,
    ],
)
def test_the_published_schema_and_the_model_reject_the_same_broken_answers(mutate) -> None:
    wire = _valid_wire()
    mutate(wire)
    with pytest.raises(jsonschema.ValidationError):
        jsonschema.validate(wire, ANSWER_SCHEMA)
    with pytest.raises(ValidationError):
        DestinationConsumersAnswer.model_validate(wire)


def test_a_next_cursor_on_an_empty_page_is_a_contract_violation_not_an_index_error() -> None:
    """Review of #592: the model must reject the shape with a ValidationError, and the published
    schema must reject it too."""
    wire = _answer(_three(), _request(limit=1))
    assert wire["data"]["page"]["next_cursor"]
    wire["data"]["rows"] = []
    wire["data"]["page"]["returned"] = 0
    with pytest.raises(jsonschema.ValidationError):
        jsonschema.validate(wire, ANSWER_SCHEMA)
    with pytest.raises(ValidationError):
        DestinationConsumersAnswer.model_validate(wire)
