"""v0.7.1 I3.1: the `get_destination_consumers` query contract and projection (I3 spec §2-§3, §6),
over hand-built snapshot states. Expected outcomes, reasons, limitation codes and row sets are
written down here from the spec and the I2 vectors, not generated by the projection; evidence refs
are checked against the frozen `evidence_ref` derivation with the exact internal ids each must
bind."""

